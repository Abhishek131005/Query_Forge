def generate_sql(question,schema,model='finetuned'):
    if not endpoint:
        q=question.lower()
        if ('department' in q or 'each' in q) and ('count' in q or 'how many' in q):
            sql = 'SELECT department, COUNT(*) AS employee_count FROM employees GROUP BY department;'
            return normalize_common_query(sql, question, schema),True
        if 'average' in q or 'avg' in q:
            sql = 'SELECT department, AVG(salary) AS average_salary FROM employees GROUP BY department;'
            return normalize_common_query(sql, question, schema),True
        if 'engineering' in q and ('salary' in q or 'earning' in q):
            threshold = re.search(r'(?:more than|over|above|greater than)\s+(\d+)', q)
            amount = threshold.group(1) if threshold else '100000'
            sql = f"SELECT name, salary FROM employees WHERE department = 'Engineering' AND salary > {amount};"
            return normalize_common_query(sql, question, schema),True
        if 'engineering' in q:
            return normalize_common_query(
                "SELECT * FROM employees WHERE department = 'Engineering';",
                question,
                schema
            ),True
        return normalize_common_query(
            'SELECT * FROM employees LIMIT 10;',
            question,
            schema
        ),True
    response=requests.post(endpoint.rstrip('/')+'/generate-sql',json={'question':question,'schema':schema,'model':model},timeout=90)
    response.raise_for_status()
    result = response.json()
    sql = result.get('sql')
    if not isinstance(sql, str) or not sql.strip():
        raise ValueError('The backend returned no SQL query.')
    return normalize_common_query(sql.strip(), question, schema),False


def normalize_common_query(sql, question, schema):
    """Correct frequent adapter mistakes while preserving other SQL output."""
    table_match = re.search(
        r'CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?["`]?(\w+)["`]?',
        schema,
        re.IGNORECASE
    )
    if not table_match:
        return sql

    table = table_match.group(1).strip('"`')
    column_matches = re.findall(
        r'\b([A-Za-z_]\w*)\s+'
        r'(?:INTEGER|REAL|NUMERIC|DECIMAL|FLOAT|DOUBLE|TEXT|VARCHAR|DATE|BOOLEAN)\b',
        schema,
        re.IGNORECASE
    )
    question_lower = question.lower()
    group_column = next(
        (
            column for column in column_matches
            if column.lower() in question_lower
            and column.lower() not in {'id', 'salary'}
        ),
        None
    )
    numeric_column = next(
        (
            column for column in column_matches
            if column.lower() in {'salary', 'amount', 'price', 'total', 'score'}
        ),
        None
    )
    grouped = bool(re.search(r'\b(each|by|per)\b', question_lower))

    if group_column and grouped and (
        'count' in question_lower or 'how many' in question_lower
    ):
        return (
            f'SELECT {group_column}, COUNT(*) AS employee_count '
            f'FROM {table} GROUP BY {group_column};'
        )
    if group_column and numeric_column and grouped and (
        'average' in question_lower or re.search(r'\bavg\b', question_lower)
    ):
        return (
            f'SELECT {group_column}, AVG({numeric_column}) '
            f'AS average_{numeric_column} FROM {table} '
            f'GROUP BY {group_column};'
        )

    # The adapter often uses its training example table name. Always bind
    # generated SQL to the actual table declared in the current schema.
    sql = re.sub(
        r'(\bFROM\s+)(["`]?\w+["`]?)',
        rf'\g<1>"{table}"',
        sql,
        count=1,
        flags=re.IGNORECASE
    )

    listing = re.search(r'\b(list|show|display|return)\b', question_lower)
    if listing and re.search(r'\bcount\s*\(', sql, re.IGNORECASE):
        where_match = re.search(r'\bWHERE\b[\s\S]*$', sql, re.IGNORECASE)
        where = f' {where_match.group(0).strip()}' if where_match else ''
        return f'SELECT * FROM {table}{where};'
    return sql

def safe_query(sql):
    if active_tables:
        return execute_sql(sql, database_path())

    # Demo database remains read-only for execution.
    # Use an isolated temporary SQLite database instead
    # of the shared in-memory demo connection.
    import tempfile
    from pathlib import Path

    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "demo.sqlite3"

        with sqlite3.connect(path) as demo_conn:
            demo_conn.execute("""
                CREATE TABLE employees (
                    id INTEGER PRIMARY KEY,
                    name TEXT,
                    department TEXT,
                    salary INTEGER
                )
            """)

            demo_conn.executemany(
                "INSERT INTO employees VALUES (?, ?, ?, ?)",
                [
                    (1, "Asha", "Engineering", 120000),
                    (2, "Rahul", "Sales", 75000),
                    (3, "Mira", "Engineering", 145000),
                    (4, "Neha", "Finance", 92000),
                    (5, "Kabir", "Engineering", 85000)
                ]
            )

        return execute_sql(sql, path)

